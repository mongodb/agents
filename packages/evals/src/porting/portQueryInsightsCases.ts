import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

import { parse } from "yaml";
import { z } from "zod";

import { renderPortedCases } from "./portAssistantCase.js";
import {
  portQueryInsightsCase,
  renderQueryInsightsSeed,
} from "./portQueryInsightsCase.js";

const ATLAS_FIXTURE_DIR = path.join(import.meta.dirname, "..", "..", "fixtures", "atlas");

const SelectionSchema = z.object({
  cases: z.array(
    z.object({
      /** File name in the source directory, such as `case_08.json`. */
      file: z.string(),
      /** Seed and case id. Defaults to the number in the file name. */
      id: z.string().optional(),
      namespace: z.string().optional(),
      planSummary: z.string().optional(),
      message: z.string().optional(),
    }),
  ),
});

const DATASET_HEADER = `Atlas Query Insights cases converted from the source eval cases.
Generated by \`pnpm port:query-insights\`. Each case names its source.
Each case reads a mock Atlas seed of the same name in fixtures/atlas.`;

const USAGE = `Usage: pnpm port:query-insights --source-dir <source eval cases dir> \\
  --select <selection.yml> [--out <dataset.yml>]

Writes one mock Atlas seed per case to fixtures/atlas, and the cases to
--out (or stdout). The selection file lists the source files to convert:

  cases:
    - { file: case_08.json }
    - { file: case_01.json, namespace: shop.visits }

--source-dir is the directory that holds the source eval case JSON files.

The references are copied as written and quote lifetime totals the agent
never sees. Rewrite them before committing the cases.`;

/** `case_08.json` is `08`, `case_14_synthetic.json` is `14`. */
function defaultId(file: string): string {
  const match = /^case_(\d+[a-z]?)/.exec(path.basename(file));
  if (!match) throw new Error(`${file}: pass an id, none in the file name`);
  return match[1];
}

function main() {
  const { values } = parseArgs({
    options: {
      "source-dir": { type: "string" },
      select: { type: "string" },
      out: { type: "string" },
    },
  });
  if (!values["source-dir"] || !values.select) {
    console.error(USAGE);
    process.exit(1);
  }

  const selection = SelectionSchema.parse(
    parse(fs.readFileSync(values.select, "utf8")),
  );
  const ported = selection.cases.map(({ file, id, ...options }) => {
    const source: unknown = JSON.parse(
      fs.readFileSync(path.join(values["source-dir"]!, file), "utf8"),
    );
    const result = portQueryInsightsCase(source, { id: id ?? defaultId(file), ...options });
    fs.writeFileSync(
      path.join(ATLAS_FIXTURE_DIR, `${result.seedName}.yml`),
      renderQueryInsightsSeed(
        result.seed,
        `Converted from the source eval cases, ${file}, by
\`pnpm port:query-insights\`. Slow-log values are per execution: the
source's lifetime totals divided by its execution count.`,
      ),
    );
    return { file, case: result.case };
  });

  const yaml = renderPortedCases(ported, DATASET_HEADER);
  if (values.out) fs.writeFileSync(values.out, yaml);
  else process.stdout.write(yaml);
}

try {
  main();
} catch (error) {
  console.error((error as Error).message);
  process.exit(1);
}
