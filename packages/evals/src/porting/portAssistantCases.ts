import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

import { parse } from "yaml";
import { z } from "zod";

import {
  portKnowledgeCase,
  renderPortedCases,
  type PortedCaseWithSource,
} from "./portAssistantCase.js";

const SelectionSchema = z.object({
  cases: z.array(
    z.object({
      file: z.string(),
      name: z.string(),
      /** Part of the user message. Needed when several cases share a name. */
      message: z.string().optional(),
    }),
  ),
});

const USAGE = `Usage: pnpm port:cases --source-dir <evalCases dir> \\
  --select <selection.yml> [--out <dataset.yml>]

The selection file lists the cases to port:

  cases:
    - { file: conversations.yml, name: "Create a cluster in Atlas" }
    - { file: version_q_and_a_conversations.yml, name: retrieves_specific_old_page, message: Rust driver 2.8 }

--source-dir is a checkout of mongodb/ai-assistant at
packages/chatbot-server-mongodb-public/evalCases.`;

const HEADER = `Knowledge questions adapted from mongodb/ai-assistant evalCases.
Copyright MongoDB, Inc. Licensed under the Apache License, Version 2.0.
Generated by \`pnpm port:cases\`. Each case names its source.`;

function findCase(
  sourceCases: { name?: unknown; input?: { messages?: { content?: unknown }[] } }[],
  file: string,
  name: string,
  message: string | undefined,
) {
  const matches = sourceCases.filter(
    (c) =>
      c.name === name &&
      (message === undefined ||
        String(c.input?.messages?.at(-1)?.content ?? "").includes(message)),
  );
  if (matches.length !== 1) {
    throw new Error(
      `${file}: "${name}"${message ? ` with message containing "${message}"` : ""} matched ${matches.length} cases, expected 1`,
    );
  }
  return matches[0];
}

function main() {
  const { values } = parseArgs({
    options: {
      "source-dir": { type: "string" },
      select: { type: "string" },
      out: { type: "string" },
    },
  });
  if (!values["source-dir"] || !values.select) {
    console.error(USAGE);
    process.exit(1);
  }

  const selection = SelectionSchema.parse(
    parse(fs.readFileSync(values.select, "utf8")),
  );
  const sourceFiles = new Map<string, unknown[]>();
  const ported: PortedCaseWithSource[] = selection.cases.map(
    ({ file, name, message }) => {
      if (!sourceFiles.has(file)) {
        const text = fs.readFileSync(path.join(values["source-dir"]!, file), "utf8");
        sourceFiles.set(file, parse(text) as unknown[]);
      }
      const source = findCase(
        sourceFiles.get(file) as never,
        file,
        name,
        message,
      );
      return { file, case: portKnowledgeCase(source) };
    },
  );

  const yaml = renderPortedCases(ported, HEADER);
  if (values.out) fs.writeFileSync(values.out, yaml);
  else process.stdout.write(yaml);
}

try {
  main();
} catch (error) {
  console.error((error as Error).message);
  process.exit(1);
}
