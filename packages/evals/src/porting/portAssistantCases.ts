import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

import { parse } from "yaml";
import { z } from "zod";

import {
  portKnowledgeCase,
  renderPortedCases,
  type PortedCaseWithSource,
} from "./portAssistantCase.js";
import { portDbToolCase } from "./portDbToolCase.js";

const SelectionSchema = z.object({
  cases: z.array(
    z.object({
      file: z.string(),
      name: z.string(),
      /** Part of the user message. Needed when several cases share a name. */
      message: z.string().optional(),
      /** New case name. Needed when sources reuse a name, as versions do. */
      as: z.string().optional(),
      /** Replaces the source description, when it describes the source's harness. */
      description: z.string().optional(),
    }),
  ),
});

const KINDS = {
  knowledge: {
    port: portKnowledgeCase,
    header: `Knowledge questions adapted from mongodb/ai-assistant evalCases.
Copyright MongoDB, Inc. Licensed under the Apache License, Version 2.0.
Generated by \`pnpm port:cases\`. Each case names its source.`,
  },
  "db-tools": {
    port: portDbToolCase,
    header: `Database tool cases for Atlas Explorer, read-only mode, adapted from
mongodb/ai-assistant evalCases. Copyright MongoDB, Inc. Licensed under the
Apache License, Version 2.0. Generated by \`pnpm port:cases --kind db-tools\`.
Each case names its source.`,
  },
} as const;

const USAGE = `Usage: pnpm port:cases --source-dir <evalCases dir> \\
  --select <selection.yml> [--kind knowledge|db-tools] [--out <dataset.yml>]

--kind defaults to knowledge. db-tools ports the read-only database tool
cases, which read the sample-mflix fixture.

The selection file lists the cases to port:

  cases:
    - { file: conversations.yml, name: "Create a cluster in Atlas" }
    - { file: version_q_and_a_conversations.yml, name: retrieves_specific_old_page, message: Rust driver 2.8, as: "Rust 2.8 find with limit" }

--source-dir is a checkout of mongodb/ai-assistant at
packages/chatbot-server-mongodb-public/evalCases.`;

function findCase(
  sourceCases: { name?: unknown; input?: { messages?: { content?: unknown }[] } }[],
  file: string,
  name: string,
  message: string | undefined,
) {
  const matches = sourceCases.filter(
    (c) =>
      c.name === name &&
      (message === undefined ||
        String(c.input?.messages?.at(-1)?.content ?? "").includes(message)),
  );
  if (matches.length !== 1) {
    throw new Error(
      `${file}: "${name}"${message ? ` with message containing "${message}"` : ""} matched ${matches.length} cases, expected 1`,
    );
  }
  return matches[0];
}

function main() {
  const { values } = parseArgs({
    options: {
      "source-dir": { type: "string" },
      select: { type: "string" },
      kind: { type: "string", default: "knowledge" },
      out: { type: "string" },
    },
  });
  if (!values["source-dir"] || !values.select || !(values.kind! in KINDS)) {
    console.error(USAGE);
    process.exit(1);
  }
  const kind = KINDS[values.kind as keyof typeof KINDS];

  const selection = SelectionSchema.parse(
    parse(fs.readFileSync(values.select, "utf8")),
  );
  const sourceFiles = new Map<string, unknown[]>();
  const ported: PortedCaseWithSource[] = selection.cases.map(
    ({ file, name, message, as, description }) => {
      if (!sourceFiles.has(file)) {
        const text = fs.readFileSync(path.join(values["source-dir"]!, file), "utf8");
        sourceFiles.set(file, parse(text) as unknown[]);
      }
      const source = findCase(
        sourceFiles.get(file) as never,
        file,
        name,
        message,
      );
      const ported = {
        ...kind.port(source),
        ...(description !== undefined && { description }),
      };
      return as === undefined
        ? { file, case: ported }
        : { file, sourceName: name, case: { ...ported, name: as } };
    },
  );

  const yaml = renderPortedCases(ported, kind.header);
  if (values.out) fs.writeFileSync(values.out, yaml);
  else process.stdout.write(yaml);
}

try {
  main();
} catch (error) {
  console.error((error as Error).message);
  process.exit(1);
}
